// Execute with Playwright MCP browser_run_code_unsafe, filename set to this file.
async (parent) => {
  const out = "D:/NASA/.cache/sprint2-acceptance";
  const context = await parent.context().browser().newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: "Asia/Jakarta", acceptDownloads: true });
  const page = await context.newPage();
  page.setDefaultTimeout(8000);
  const failures = [];
  page.on("pageerror", error => failures.push(error.message));
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const assertText = async (locator, text) => { await locator.getByText(text, { exact: true }).waitFor(); };
  const downloads = [];
  try {
    await page.goto("http://localhost:3005/simulation");
    await page.getByRole("button", { name: "Analisis historis", exact: true }).click();
    await page.getByRole("button", { name: "Lihat contoh sintetis", exact: true }).click();
    await page.getByRole("button", { name: "Muat titik mentah hasil", exact: true }).click();
    await page.locator("summary").filter({ hasText: "Batas viewport" }).click();
    for (const [field, value] of Object.entries({ west: 113, south: -3.5, east: 115, north: -1.5 })) await page.locator(`.global-bounds input[name=${field}]`).fill(String(value));
    await page.getByRole("button", { name: "Tampilkan area", exact: true }).click();
    const canvas = page.locator("canvas.maplibregl-canvas");
    await canvas.scrollIntoViewIfNeeded();
    await page.waitForTimeout(800);
    const mapWidth = async () => Number(await page.locator('.global-bounds input[name=east]').inputValue()) - Number(await page.locator('.global-bounds input[name=west]').inputValue());
    const before = await mapWidth();
    let box = await canvas.boundingBox();
    await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
    await page.waitForTimeout(900);
    check(await mapWidth() < before / 2, "Heatmap click must zoom into the concentration");
    await page.getByRole("button", { name: "Titik hotspot", exact: true }).click();
    await canvas.scrollIntoViewIfNeeded();
    await page.waitForTimeout(400);
    box = await canvas.boundingBox();
    await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
    await page.getByRole("heading", { name: "Tandai lokasi", exact: true }).waitFor();
    await page.getByRole("button", { name: "Anomali", exact: true }).click();
    check((await page.locator(".calendar-cell").innerText()).includes("Persentil tidak tersedia"), "Missing percentile must be explicit");
    await page.locator(".calendar-cell").click();
    await page.getByText("Detail harian", { exact: false }).last().waitFor();
    const scope = page.getByRole("region", { name: "Lokasi pemantauan", exact: true });
    await scope.getByRole("button", { name: "Lihat deteksi", exact: true }).click();
    await scope.getByLabel("Nama lokasi", { exact: true }).fill("Acceptance location");
    await scope.getByLabel("Ditandai oleh (nama lokal)", { exact: true }).fill("Researcher");
    await scope.getByRole("button", { name: "Simpan lokasi", exact: true }).click();
    await assertText(scope, "Lokasi disimpan dengan bukti awalnya.");
    await scope.getByLabel("Penanggung jawab", { exact: true }).fill("Inspector");
    await scope.getByLabel("Pencatat penugasan", { exact: true }).fill("Coordinator");
    await scope.getByRole("button", { name: "Buat penugasan", exact: true }).click();
    await assertText(scope, "Tersimpan di browser ini.");
    await scope.getByRole("combobox", { name: "Pilih penugasan", exact: true }).selectOption({ index: 1 });
    await scope.getByLabel("Pencatat", { exact: true }).fill("Recorder");
    await scope.getByLabel("Waktu pemeriksaan (waktu lokal)", { exact: true }).fill("2026-11-12T08:30");
    await scope.getByRole("textbox", { name: "Catatan", exact: true }).fill("Initial inspection");
    await scope.getByRole("button", { name: "Simpan pemeriksaan", exact: true }).click();
    await assertText(scope, "Initial inspection");
    await scope.getByRole("button", { name: "Koreksi laporan", exact: true }).click();
    check(await scope.getByRole("textbox", { name: "Catatan", exact: true }).inputValue() === "Initial inspection", "Correction must preload previous notes");
    await scope.getByLabel("Pencatat", { exact: true }).fill("Editor");
    await scope.getByRole("textbox", { name: "Catatan", exact: true }).fill("Corrected inspection");
    await scope.getByLabel("Alasan koreksi", { exact: true }).fill("Clarify notes");
    await scope.getByRole("button", { name: "Simpan pemeriksaan", exact: true }).click();
    await assertText(scope, "Corrected inspection");
    await scope.getByRole("combobox", { name: "Status pekerjaan", exact: true }).selectOption("completed");
    await scope.getByLabel("Diubah oleh", { exact: true }).fill("Coordinator");
    await scope.getByRole("button", { name: "Perbarui status", exact: true }).click();
    await scope.getByRole("combobox", { name: "Status pekerjaan", exact: true }).waitFor({ state: "detached" });
    await page.reload();
    await page.getByRole("button", { name: "Analisis historis", exact: true }).click();
    await scope.getByRole("combobox", { name: "Lokasi tersimpan", exact: true }).selectOption({ index: 1 });
    await scope.getByRole("combobox", { name: "Pilih penugasan", exact: true }).selectOption({ index: 1 });
    await assertText(scope, "Corrected inspection");
    check(await scope.getByRole("combobox", { name: "Status pekerjaan", exact: true }).count() === 0, "Completed assignment must persist after reload");
    await scope.getByRole("button", { name: "Gunakan area untuk analisis berikutnya", exact: true }).click();
    check(await page.getByRole("textbox", { name: "Nama area", exact: true }).inputValue() === "Synthetic custom AOI", "Follow-up must reuse original area");
    await page.getByRole("button", { name: "Lihat contoh sintetis", exact: true }).click();
    for (const [label, suffix] of [["CSV deteksi asli", "csv"], ["CSV agregat", "csv"], ["JSON + manifest", "json"], ["PNG kalender", "png"]]) {
      const pending = page.waitForEvent("download");
      await page.getByRole("button", { name: label, exact: true }).click();
      const download = await pending;
      const name = download.suggestedFilename();
      await download.saveAs(`${out}/${name}`);
      const stream = await download.createReadStream();
      const chunks = [];
      for await (const chunk of stream) chunks.push(chunk);
      const bytes = Buffer.concat(chunks);
      check(bytes.length > 50 && name.includes("demo"), "Download must carry demo mode and content");
      if (suffix === "png") check(bytes.subarray(1, 4).toString() === "PNG", "PNG signature");
      if (label === "CSV deteksi asli") check(bytes.toString().split("\r\n").length === 2 && bytes.toString().includes("detection-demo"), "Raw CSV contains only original fixture observation");
      if (suffix === "json") check(JSON.parse(bytes).result.id === "analysis-demo", "JSON result identity");
      downloads.push(name);
    }
    await page.getByRole("combobox", { name: "Bahasa", exact: true }).selectOption("en");
    const results = page.locator(".research-results");
    await results.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${out}/desktop-en.png`, fullPage: true });
    await results.screenshot({ path: `${out}/calendar-desktop.png` });
    await page.locator(".research-monitoring").screenshot({ path: `${out}/monitoring-desktop.png` });
    await page.setViewportSize({ width: 390, height: 844 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile must not overflow horizontally");
    await page.screenshot({ path: `${out}/mobile-en.png`, fullPage: true });
    await results.screenshot({ path: `${out}/calendar-mobile.png` });
    await page.locator(".research-monitoring").screenshot({ path: `${out}/monitoring-mobile.png` });
    check(failures.length === 0, `Runtime exceptions: ${failures.join("; ")}`);
    const result = { passed: true, synthetic: true, downloads, runtimeExceptions: failures, checks: ["heatmap click zoom", "map point opens original evidence", "calendar count/anomaly", "daily detail", "original anchor", "assignment", "report", "correction history", "terminal status", "reload persistence", "follow-up AOI", "CSV/JSON/PNG", "EN/ID", "mobile overflow"] };
    return result;
  } catch(error) { await page.screenshot({path:`${out}/failure.png`,fullPage:true}); throw error; }
  finally { await context.close(); }
}
